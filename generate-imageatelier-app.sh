#!/usr/bin/env bash
# Build ImageAtelier.app: a thin launcher for ./local.sh in this folder (the repo path is baked in; regenerate if it moves).
#   ./generate-imageatelier-app.sh                 creates ./ImageAtelier.app
#   ./generate-imageatelier-app.sh ~/Applications  creates ~/Applications/ImageAtelier.app (any folder, e.g. /Applications)
# Logs go to data-local/logs/launcher.log; if the launch fails, an alert shows the end of that log.
set -euo pipefail
cd "$(dirname "$0")"
REPO="$PWD"
DEST="${1:-$REPO}"
APP="$DEST/ImageAtelier.app"
ICON_PNG="$REPO/imageatelier/static/icons/icon-1024.png"
[[ -f "$ICON_PNG" ]] || ICON_PNG="$REPO/imageatelier/static/icons/icon-512.png"  # fallback when no 1024px source

[[ -x "$REPO/local.sh" ]] || { echo "error: $REPO/local.sh is missing or not executable" >&2; exit 1; }
[[ -d "$DEST" ]] || { echo "error: destination folder $DEST does not exist" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
build="$tmp/ImageAtelier.app"
mkdir -p "$build/Contents/MacOS" "$build/Contents/Resources"

cat > "$build/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>ImageAtelier</string>
  <key>CFBundleDisplayName</key><string>ImageAtelier</string>
  <key>CFBundleIdentifier</key><string>local.imageatelier.launcher</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>ImageAtelier</string>
  <key>CFBundleIconFile</key><string>ImageAtelier</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>LSArchitecturePriority</key><array><string>arm64</string></array>
  <!-- The launcher itself stays out of the Dock; the ImageAtelier window (Python) gets the Dock icon. -->
  <key>LSUIElement</key><true/>
</dict>
</plist>
EOF

# printf %q bakes the repo path in safely even if it contains spaces or quotes.
{
  echo '#!/usr/bin/env bash'
  echo '# Generated by generate-imageatelier-app.sh: runs local.sh from the repo below, logging to its data dir.'
  printf 'REPO=%q\n' "$REPO"
  cat <<'EOF'
# Finder launches apps with a bare PATH; local.sh may need uv to install the GUI extra.
export PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:$HOME/.cargo/bin:/usr/bin:/bin:/usr/sbin:/sbin"
LOGS="${IMAGEATELIER_DATA:-$REPO/data-local}/logs"
LOG="$LOGS/launcher.log"
alert() {
  /usr/bin/osascript - "$1" <<'OSA' >/dev/null 2>&1
on run argv
  display alert "ImageAtelier could not start" message (item 1 of argv) as critical
end run
OSA
}
if [[ ! -x "$REPO/local.sh" ]]; then
  alert "local.sh was not found in $REPO. Regenerate ImageAtelier.app with generate-imageatelier-app.sh."
  exit 1
fi
mkdir -p "$LOGS"
printf '\n==> %s launching %s/local.sh\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$REPO" >> "$LOG"
"$REPO/local.sh" >> "$LOG" 2>&1 < /dev/null
code=$?
if [[ $code -ne 0 ]]; then
  alert "local.sh exited with code $code. End of $LOG:

$(tail -n 12 "$LOG")"
fi
exit "$code"
EOF
} > "$build/Contents/MacOS/ImageAtelier"
chmod +x "$build/Contents/MacOS/ImageAtelier"

if [[ -f "$ICON_PNG" ]]; then
  iconset="$tmp/ImageAtelier.iconset"
  mkdir "$iconset"
  src_px="$(sips -g pixelWidth "$ICON_PNG" | awk '/pixelWidth/ {print $2}')"
  for size in 16 32 128 256 512; do
    sips -z "$size" "$size" "$ICON_PNG" --out "$iconset/icon_${size}x${size}.png" >/dev/null
    double=$((size * 2))
    [[ $double -le $src_px ]] && sips -z "$double" "$double" "$ICON_PNG" --out "$iconset/icon_${size}x${size}@2x.png" >/dev/null
  done
  iconutil -c icns "$iconset" -o "$build/Contents/Resources/ImageAtelier.icns"
fi

# Replace an older copy only once the new one is fully built.
rm -rf "$APP"
mv "$build" "$APP"
touch "$APP"  # nudge Finder/LaunchServices to pick up the new icon
echo "created $APP -> $REPO/local.sh"
